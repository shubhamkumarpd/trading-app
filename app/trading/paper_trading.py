
from datetime import datetime, timezone
from uuid import uuid4

from app.trading.trade_logger import TradeLogger


class PaperTradingEngine:

    def __init__(self, initial_capital=100000, trade_logger=None):
        if initial_capital <= 0:
            raise ValueError("Initial capital must be positive.")

        self.initial_capital = float(initial_capital)
        self.cash = float(initial_capital)
        self.open_positions = []
        self.closed_trades = []

        self.trade_logger = trade_logger or TradeLogger()

    def open_trade(self, signal, quantity):
        action = signal.get("action")

        if action not in ("BUY", "SELL"):
            raise ValueError("Only BUY and SELL trades are allowed.")

        # Signals generated by the analysis module use ``entry_price``.  Keep
        # ``entry`` as a backward-compatible alias for older callers.
        entry_value = signal.get("entry_price", signal.get("entry"))
        if entry_value is None:
            raise ValueError("Signal must include an entry price.")

        entry = float(entry_value)
        stop_loss = float(signal["stop_loss"])
        target = float(signal["target"])

        if quantity <= 0 or entry <= 0:
            raise ValueError("Invalid quantity or entry price.")

        if action == "BUY" and not stop_loss < entry < target:
            raise ValueError("Invalid BUY trade prices.")

        if action == "SELL" and not target < entry < stop_loss:
            raise ValueError("Invalid SELL trade prices.")

        capital_required = entry * quantity

        if capital_required > self.cash:
            raise ValueError("Insufficient available cash.")

        trade = {
            "trade_id": str(uuid4()),
            "symbol": signal.get("symbol", "UNKNOWN"),
            "action": action,
            "entry_price": entry,
            "stop_loss": stop_loss,
            "target": target,
            "quantity": int(quantity),
            "status": "OPEN",
            "opened_at": datetime.now(timezone.utc).isoformat(),
        }

        self.cash -= capital_required
        self.open_positions.append(trade)

        self.trade_logger.log_trade(trade)

        return trade

    def close_trade(self, trade_id, exit_price, reason="MANUAL", charges=0):
        exit_price = float(exit_price)
        charges = float(charges)

        if exit_price <= 0:
            raise ValueError("Exit price must be positive.")

        if charges < 0:
            raise ValueError("Charges cannot be negative.")

        trade = next(
            (
                item for item in self.open_positions
                if item["trade_id"] == trade_id
            ),
            None,
        )

        if trade is None:
            raise ValueError("Open trade not found.")

        entry = trade["entry_price"]
        quantity = trade["quantity"]

        if trade["action"] == "BUY":
            gross_pnl = (exit_price - entry) * quantity
        else:
            gross_pnl = (entry - exit_price) * quantity

        net_pnl = gross_pnl - charges

        self.cash += (entry * quantity) + net_pnl

        trade.update({
            "exit_price": exit_price,
            "gross_pnl": round(gross_pnl, 2),
            "charges": round(charges, 2),
            "net_pnl": round(net_pnl, 2),
            "pnl": round(net_pnl, 2),
            "status": "CLOSED",
            "exit_reason": reason,
            "closed_at": datetime.now(timezone.utc).isoformat(),
        })

        self.open_positions.remove(trade)
        self.closed_trades.append(trade)

        self.trade_logger.update_trade(trade)

        return trade

    def get_summary(self):
        realised_pnl = sum(
            trade["pnl"] for trade in self.closed_trades
        )

        return {
            "initial_capital": self.initial_capital,
            "available_cash": round(self.cash, 2),
            "open_positions": len(self.open_positions),
            "closed_trades": len(self.closed_trades),
            "realised_pnl": round(realised_pnl, 2),
            "total_equity": round(
                self.cash
                + sum(
                    t["entry_price"] * t["quantity"]
                    for t in self.open_positions
                ),
                2,
            ),
        }
